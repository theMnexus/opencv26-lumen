"""Ghost removal on real brackets, scored against a motion-free reference.

    uv run python bench/ghost_real.py data/cambridge/jpg

Each scene of the Cambridge deghosting dataset (CC BY 4.0) has a test bracket
with motion (`ghosted/`) and the same bracket without motion (`ground_truth/`).
Both share the middle frame, so a perfect deghost reproduces the reference merge.

Per scene: align + merge the test bracket with ghost removal on and off, merge
the reference bracket the same way, and compare each against it (PSNR, SSIM).
The full agent also runs on the test bracket, so its decision is recorded.
Writes docs/RESULTS-ghost.md and docs/RESULTS-ghost.csv.
"""

from __future__ import annotations

import argparse
import csv
import statistics
import time
from pathlib import Path

import cv2
import numpy as np

from lumen.agent import run_set
from lumen.align import align_set
from lumen.io import load_frame
from lumen.merge import merge_set

ROOT = Path(__file__).resolve().parents[1]
REDUCE = 2  # 10 MP camera JPEGs -> 2.5 MP: same ranking, a quarter of the time
SOURCE = ("Multi-exposure image stacks for testing HDR deghosting methods, K. Karaduzovic-Hadziabdic, "
          "J. Hasic Telalovic, R. K. Mantiuk, University of Cambridge, CC BY 4.0, doi:10.17863/CAM.6881")


def _frames(folder: Path) -> list:
    return [load_frame(p, REDUCE) for p in sorted(folder.glob("*.jpg"))]


def _merge(frames: list, deghost: bool) -> tuple[np.ndarray, float]:
    aligned = align_set([f.image for f in frames])
    merged = merge_set(aligned.aligned, aligned.reference_index, deghost=deghost)
    return merged.image, merged.ghost_ratio


def _ssim(a: np.ndarray, b: np.ndarray) -> float:
    grey = [cv2.cvtColor(x, cv2.COLOR_BGR2GRAY) for x in (a, b)]
    score, _ = cv2.quality.QualitySSIM_compute(grey[0], grey[1])
    return float(score[0])


def score_scene(scene: Path) -> dict:
    started = time.time()
    test, reference = _frames(scene / "ghosted"), _frames(scene / "ground_truth")
    truth, _ = _merge(reference, deghost=False)
    on, flagged = _merge(test, deghost=True)
    off, _ = _merge(test, deghost=False)
    state = run_set(test)
    return {"scene": scene.name, "category": scene.name.rsplit("-", 1)[0], "frames": len(test),
            "flagged": round(flagged, 4),
            "psnr_off": round(cv2.PSNR(off, truth), 2), "psnr_on": round(cv2.PSNR(on, truth), 2),
            "ssim_off": round(_ssim(off, truth), 4), "ssim_on": round(_ssim(on, truth), 4),
            "agent": state.status, "agent_reason": state.reason,
            "seconds": round(time.time() - started, 1)}


def _summary(rows: list[dict]) -> list[str]:
    gain = [r["psnr_on"] - r["psnr_off"] for r in rows]
    lines = [f"Scenes: {len(rows)}. Ghost removal on vs off, both compared with the motion-free merge:", "",
             f"- PSNR: {statistics.mean(r['psnr_off'] for r in rows):.2f} dB off → "
             f"{statistics.mean(r['psnr_on'] for r in rows):.2f} dB on (mean gain {statistics.mean(gain):+.2f} dB, "
             f"better in {sum(g > 0.05 for g in gain)}, worse in {sum(g < -0.05 for g in gain)}, same in "
             f"{sum(abs(g) <= 0.05 for g in gain)})",
             f"- SSIM: {statistics.mean(r['ssim_off'] for r in rows):.4f} off → "
             f"{statistics.mean(r['ssim_on'] for r in rows):.4f} on",
             f"- Agent on the test bracket: {sum(r['agent'] == 'ok' for r in rows)} ok, "
             f"{sum(r['agent'] == 'needs_review' for r in rows)} needs_review", "",
             "| Category | Scenes | PSNR off → on (dB) | SSIM off → on | Flagged |", "|---|---|---|---|---|"]
    for cat in sorted({r["category"] for r in rows}):
        rs = [r for r in rows if r["category"] == cat]
        lines.append(f"| {cat} | {len(rs)} | {statistics.mean(r['psnr_off'] for r in rs):.2f} → "
                     f"{statistics.mean(r['psnr_on'] for r in rs):.2f} | "
                     f"{statistics.mean(r['ssim_off'] for r in rs):.4f} → {statistics.mean(r['ssim_on'] for r in rs):.4f} | "
                     f"{statistics.mean(r['flagged'] for r in rs):.1%} |")
    return lines


def write(rows: list[dict], out_md: Path, out_csv: Path) -> None:
    with out_csv.open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    lines = ["# Results — ghost removal on real brackets", "", f"Source: {SOURCE}", "",
             f"Generated by `uv run python bench/ghost_real.py`; frames decoded at 1/{REDUCE} size. "
             f"Raw numbers: `{out_csv.relative_to(ROOT) if out_csv.is_relative_to(ROOT) else out_csv}`.", ""]
    lines += _summary(rows)
    lines += ["", "| Scene | Flagged | PSNR off → on | SSIM off → on | Agent |", "|---|---|---|---|---|"]
    lines += [f"| {r['scene']} | {r['flagged']:.1%} | {r['psnr_off']:.2f} → {r['psnr_on']:.2f} | "
              f"{r['ssim_off']:.4f} → {r['ssim_on']:.4f} | {r['agent']} {r['agent_reason']} |" for r in rows]
    out_md.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("folder", type=Path, help="one subfolder per scene, each with ghosted/ and ground_truth/")
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "RESULTS-ghost.md")
    args = parser.parse_args()
    scenes = sorted(d for d in args.folder.iterdir() if (d / "ghosted").is_dir() and (d / "ground_truth").is_dir())
    if not scenes:
        raise SystemExit(f"no scenes with ghosted/ and ground_truth/ in {args.folder}")
    rows = []
    for scene in scenes:
        rows.append(score_scene(scene))
        r = rows[-1]
        print(f"{r['scene']}: PSNR {r['psnr_off']} -> {r['psnr_on']}  flagged {r['flagged']:.1%}  {r['agent']}", flush=True)
    out = args.out.resolve()
    write(rows, out, out.with_suffix(".csv"))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
